-- Find the percentage of customers who have placed at least one order.

-- Return:

-- customer_order_rate as a percentage rounded to 2 decimal places.


select 
    round(
        (customer_with_orders/ total_customers) *100
        ,2
    ) as customer_order_rate 
from 
    (
        SELECT
            COUNT(DISTINCT CASE
                WHEN o.order_id IS NOT NULL THEN c.customer_id
            END) AS customer_with_orders,
        
            COUNT(DISTINCT c.customer_id) AS total_customers
        
        FROM customers c
        LEFT JOIN orders o
            ON c.customer_id = o.customer_id
        
    ) as customer_stats



--  Find the total revenue generated by each customer and classify customers into:

-- High Value → total spending ≥ 10,000
-- Medium Value → total spending between 5,000 and 9,999
-- Low Value → total spending < 5,000

-- Return:

-- customer_id
-- customer_name
-- total_spent
-- customer_value_segment


select 
    c.customer_id,
    c.customer_name,
    sum(o.order_total) as total_spent,
    case 
        when sum(o.order_total) >= 10000 then 'high value'
        when sum(o.order_total) between 5000 and 9999 then 'medium value'
        else 'low value'
        end as customer_value_segment
from 
    customers c
left join 
    orders o 
on c.customer_id = o.customer_id
group by c.customer_id, c.customer_name



