-- Q48. Find the first month in which cumulative revenue exceeded 50% of total revenue.
WITH monthly_revenue AS (
    SELECT
        DATE_FORMAT(order_date, '%Y-%m') AS month,
        SUM(order_total) AS monthly_revenue
    FROM orders
    GROUP BY DATE_FORMAT(order_date, '%Y-%m')
),
cumulative_sales AS (
    SELECT
        month,
        monthly_revenue,
        SUM(monthly_revenue) OVER (
            ORDER BY month
        ) AS cumulative_revenue
    FROM monthly_revenue
),
revenue_percentage AS (
    SELECT
        month,
        cumulative_revenue,
        ROUND(
            (
                cumulative_revenue
                / (SELECT SUM(order_total) FROM orders)
            ) * 100,
            2
        ) AS total_revenue_percentage
    FROM cumulative_sales
)
SELECT
    month,
    ROUND(cumulative_revenue, 2) AS cumulative_revenue,
    total_revenue_percentage
FROM revenue_percentage
WHERE total_revenue_percentage > 50
ORDER BY month
LIMIT 1;


