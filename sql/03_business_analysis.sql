    p.product_name,
    p.category
)

ranked-products as (select 
    product_id,
    product_name,
    category,
    total_revenue,
    rank() over (
        partition by category
        order by total_revenue desc
    ) as category_rank
from
    product_revenue
)

SELECT
    product_id,
    product_name,
    category,
    total_revenue,
    category_rank
FROM ranked_products
WHERE category_rank <= 3
ORDER BY category, category_rank;

