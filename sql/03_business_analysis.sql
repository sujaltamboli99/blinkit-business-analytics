    SELECT
        p.category,
        ROUND(SUM(o.quantity * o.unit_price), 2) AS total_revenue
    FROM products p
    LEFT JOIN order_items o
        ON p.product_id = o.product_id
    GROUP BY p.category
)

SELECT
    ROUND(AVG(total_revenue), 2) AS average_category_revenue
FROM category_revenue;




