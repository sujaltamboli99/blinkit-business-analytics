FROM customers c
LEFT JOIN orders o
    ON c.customer_id = o.customer_id
WHERE o.order_id IS NOT NULL;


-- Q15. Find the number of customers who have never placed an order.
SELECT COUNT(DISTINCT c.customer_id) AS customers_without_orders
FROM customers c
LEFT JOIN orders o
    ON c.customer_id = o.customer_id
WHERE o.order_id IS NULL;


-- Q16. Find the percentage of customers who have placed at least one order.
SELECT
    ROUND(
        (customer_with_orders / total_customers) * 100,
        2
    ) AS customer_order_rate
FROM (
    SELECT
        COUNT(DISTINCT CASE
            WHEN o.order_id IS NOT NULL THEN c.customer_id
        END) AS customer_with_orders,
        COUNT(DISTINCT c.customer_id) AS total_customers
    FROM customers c
    LEFT JOIN orders o
        ON c.customer_id = o.customer_id
) AS customer_stats;


-- Q17. Classify customers into High, Medium, and Low value segments.
SELECT
    c.customer_id,
    c.customer_name,
    SUM(o.order_total) AS total_spent,
    CASE
        WHEN SUM(o.order_total) >= 10000 THEN 'High Value'
        WHEN SUM(o.order_total) BETWEEN 5000 AND 9999 THEN 'Medium Value'
        ELSE 'Low Value'
    END AS customer_value_segment
FROM customers c
LEFT JOIN orders o
    ON c.customer_id = o.customer_id
GROUP BY c.customer_id, c.customer_name;


