-- Find the rank of each product within its category based on total revenue.

-- Return:

-- product_id
-- product_name
-- category
-- total_revenue
-- category_rank


with product_revenue as(
select 
    p.product_id,
    p.product_name,
    p.category,
    round(sum(o.quantity * o.unit_price),2) as total_revenue
from
    products p
left join 
    order_items o
on 
    p.product_id = o.product_id
group by 
    p.product_id,
    p.product_name,
    p.category
)

select 
    product_id ,
    product_name,
    category,
    total_revenue,
    rank() over (
        partition by category  
        order by total_revenue desc
    ) as category_rank
from 
    product_revenue
order by category, category_rank


